"""Generated badge consumer contracts; no retained-game transaction or input.

Badge pixels, PNG identities and local resources are real generated bytes read
by the production helpers. Names, prices and page geometry are explicit test
predicates, not native OCR measurements. The Worker fixture has inert transport;
these tests stop at eligibility/authorization and invent no purchase outcome.
"""
from __future__ import annotations

